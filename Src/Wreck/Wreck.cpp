#include <stdlib.h>
#include <math.h>
#include <windows.h>

// ==============================================================
// Wreck class
// ==============================================================

class Wreck : public VESSEL3 {
public:
	Wreck (OBJHANDLE hVessel, int flightmodel);
	void clbkSetClassCaps (FILEHANDLE cfg);
	void clbkSetStateEx (const void *status);
	void clbkPostCreation ();
	void clbkPreStep (double simt, double simdt, double mjd);
private:
	void GenerateRandomMesh ();
	double m_tet[4][3];   // 4 contact points from the generated polyhedron
};

Wreck::Wreck (OBJHANDLE hVessel, int flightmodel)
	: VESSEL3 (hVessel, flightmodel)
{
}

void Wreck::clbkSetClassCaps (FILEHANDLE cfg)
{
	// basic physical properties (small debris piece)
	char *nm = GetName ();
	if (nm && strncmp (nm, "WRECK-S", 7) == 0) SetSize (8.0);   // hull slice piece
	else SetSize (5.0);   // ~ contact point radius (the tetrahedron vertices)
	SetEmptyMass (500.0);   // heavier debris: the contact force/mass ratio stays small
	SetPMI (_V (1.2, 1.2, 1.2));
	SetMaxThrust (ENGINE_MAIN, 0.0);
	SetMaxThrust (ENGINE_RETRO, 0.0);
	SetMaxThrust (ENGINE_HOVER, 0.0);
	SetMaxThrust (ENGINE_ATTITUDE, 0.0);
	// Collision hull:
	//   points 0-2: "gear" points placed at the centre (they are inside the
	//               tetrahedron, so they never touch the ground and their friction
	//               parameters are irrelevant),
	//   points 3-6: body points at the vertices of a regular tetrahedron around
	//               the centre. The core assigns the unified hull parameters
	//               (k = 5e5, damping ratio 1.2, mu = 100) to points 3..N, so
	//               whichever tetrahedron vertex touches the ground gets them.
	// This way the wreck lands on a proper body point in every orientation.
	const double RT = 8.0;                       // tetrahedron circumradius [m]
	const double sr = 1.0 / 1.7320508075688772;  // 1/sqrt(3)
	static TOUCHDOWNVTX s_tdvtx[7] = {
		// 0-2: centre "gear" points (small triangle, never contacts)
		{ _V( 0.5, 0.0,  0.0), 5e5, 38000.0, 20.0, 20.0 },
		{ _V(-0.25, 0.0,  0.433), 5e5, 38000.0, 20.0, 20.0 },
		{ _V(-0.25, 0.0, -0.433), 5e5, 38000.0, 20.0, 20.0 },
		// 3-6: body points = regular tetrahedron vertices
		{ _V( RT*sr,  RT*sr,  RT*sr), 5e5, 18600.0, 100.0 },
		{ _V( RT*sr, -RT*sr, -RT*sr), 5e5, 18600.0, 100.0 },
		{ _V(-RT*sr,  RT*sr, -RT*sr), 5e5, 18600.0, 100.0 },
		{ _V(-RT*sr, -RT*sr,  RT*sr), 5e5, 18600.0, 100.0 }
	};
	SetTouchdownPoints (s_tdvtx, 7);


	// mesh is generated per instance in clbkPostCreation
}

void Wreck::clbkSetStateEx (const void *status)
{
	// apply the initial state given by the core when the vessel is created
	DefSetStateEx (status);
}

void Wreck::clbkPostCreation ()
{
	// hull slice piece: load the mesh generated by the core (Meshes\Wreck\slice_<seq>)
	char *nm = GetName ();
	if (nm && strncmp (nm, "WRECK-S", 7) == 0) {
		int seq = atoi (nm + 7);
		char loadname[256];
		sprintf_s (loadname, 256, "Wreck\\\\slice_%d", seq);
		MESHHANDLE hSlice = oapiLoadMeshGlobal (loadname);
		if (hSlice) {
			AddMesh (hSlice);
			// temporary mesh file: delete it after loading (no persistent mesh data)
			{
				char delPath[256];
				sprintf_s (delPath, 256, "Meshes\\Wreck\\slice_%d.msh", seq);
				DeleteFileA (delPath);
			}
			// collision hull for the slice: 3 centre points + 4 body points
			// (unified parameters are applied by the core to points 3..N)
			TOUCHDOWNVTX td[7];
			td[0].pos = _V( 0.5, 0.0, 0.0);
			td[1].pos = _V(-0.25, 0.0, 0.433);
			td[2].pos = _V(-0.25, 0.0, -0.433);
			for (int i = 0; i < 7; i++) {
				td[i].stiffness = 5e5;
				td[i].damping   = 38000.0;   // damping matched to the 5e5 stiffness (zeta ~ 1.2)
				td[i].mu        = 20.0;
				td[i].mu_lng    = 20.0;
			}
			double R = 6.0;   // contact radius for slice pieces
			td[3].pos = _V( R*0.577,  R*0.577,  R*0.577);
			td[4].pos = _V( R*0.577, -R*0.577, -R*0.577);
			td[5].pos = _V(-R*0.577,  R*0.577, -R*0.577);
			td[6].pos = _V(-R*0.577, -R*0.577,  R*0.577);
			SetTouchdownPoints (td, 7);
			return;
		}
	}
	// fall back to a random polyhedron
	GenerateRandomMesh ();

	// collision hull: 3 centre "gear" points (never touch the ground) + the 4
	// tetrahedron points chosen on the generated polyhedron (the core assigns the
	// unified hull parameters to points 3..N, so whichever point touches the ground
	// gets the good parameters)
	TOUCHDOWNVTX td[7];
	td[0].pos = _V( 0.5, 0.0, 0.0);
	td[1].pos = _V(-0.25, 0.0, 0.433);
	td[2].pos = _V(-0.25, 0.0, -0.433);
	for (int i = 0; i < 7; i++) {
		td[i].stiffness = 5e5;
		td[i].damping   = 38000.0;   // damping matched to the 5e5 stiffness (zeta ~ 1.2)   // zeta = 1.2 for m = 500 kg
		td[i].mu        = 20.0;
		td[i].mu_lng    = 20.0;
	}
	for (int p = 0; p < 4; p++) {
		td[3+p].pos = _V (m_tet[p][0], m_tet[p][1], m_tet[p][2]);
	}
	SetTouchdownPoints (td, 7);
}

void Wreck::clbkPreStep (double simt, double simdt, double mjd)
{
	// no angular momentum interaction: wrecks do not tumble (for debugging)
	SetAngularVel (_V (0, 0, 0));
}

void Wreck::GenerateRandomMesh ()
{
	// icosahedron vertices/faces (unit sphere)
	const double t = (1.0 + sqrt (5.0)) / 2.0;
	double v[12][3] = {
		{-1,  t,  0}, { 1,  t,  0}, {-1, -t,  0}, { 1, -t,  0},
		{ 0, -1,  t}, { 0,  1,  t}, { 0, -1, -t}, { 0,  1, -t},
		{ t,  0, -1}, { t,  0,  1}, {-t,  0, -1}, {-t,  0,  1}
	};
	int f[20][3] = {
		{0,11,5},{0,5,1},{0,1,7},{0,7,10},{0,10,11},
		{1,5,9},{5,11,4},{11,10,2},{10,7,6},{7,1,8},
		{3,9,4},{3,4,2},{3,2,6},{3,6,8},{3,8,9},
		{4,9,5},{2,4,11},{6,2,10},{8,6,7},{9,8,1}
	};

	// random per-vertex radius (0.65..1.35) and random scale; the span of the
	double rs[12];
	double scale = 3.5;    // keeps the polyhedron span below 10 m (max vertex radius ~4.7 m)
	for (int i = 0; i < 12; i++) {
		double r = 0.65 + 0.7 * (oapiRand());
		double l = sqrt (v[i][0]*v[i][0] + v[i][1]*v[i][1] + v[i][2]*v[i][2]);
		v[i][0] = v[i][0] / l * r;
		v[i][1] = v[i][1] / l * r;
		v[i][2] = v[i][2] / l * r;
		rs[i] = r;
	}

	// choose 4 vertices forming a tetrahedron that is as regular as possible:
	// maximise the minimum pairwise distance (12 choose 4 = 495 combinations)
	{
		int best[4] = {0, 1, 2, 3};
		double bestMin = -1.0;
		for (int a = 0; a < 9; a++) for (int b = a+1; b < 10; b++)
		for (int c = b+1; c < 11; c++) for (int d = c+1; d < 12; d++) {
			int idx[4] = {a, b, c, d};
			double dmin = 1e30;
			for (int q = 0; q < 4; q++) for (int r = q+1; r < 4; r++) {
				double dx = v[idx[q]][0]-v[idx[r]][0];
				double dy = v[idx[q]][1]-v[idx[r]][1];
				double dz = v[idx[q]][2]-v[idx[r]][2];
				double dd = sqrt (dx*dx + dy*dy + dz*dz);
				if (dd < dmin) dmin = dd;
			}
			if (dmin > bestMin) {
				bestMin = dmin;
				best[0] = a; best[1] = b; best[2] = c; best[3] = d;
			}
		}
		for (int p = 0; p < 4; p++) {
			m_tet[p][0] = scale * v[best[p]][0];
			m_tet[p][1] = scale * v[best[p]][1];
			m_tet[p][2] = scale * v[best[p]][2];
		}
	}

	// Build the mesh directly in memory via the official mesh API (no
	// temporary file on disk, no mesh load round-trip).
	NTVERTEX vtx[12];
	WORD idx[60];
	for (int i = 0; i < 12; i++) {
		double l = sqrt (v[i][0]*v[i][0] + v[i][1]*v[i][1] + v[i][2]*v[i][2]);
		if (l < 1e-9) l = 1.0;
		vtx[i].x  = (float)(scale * v[i][0]);
		vtx[i].y  = (float)(scale * v[i][1]);
		vtx[i].z  = (float)(scale * v[i][2]);
		vtx[i].nx = (float)(v[i][0]/l);
		vtx[i].ny = (float)(v[i][1]/l);
		vtx[i].nz = (float)(v[i][2]/l);
		vtx[i].tu = 0.0f;
		vtx[i].tv = 0.0f;
	}
	for (int i = 0; i < 20; i++) {
		idx[3*i+0] = (WORD)f[i][0];
		idx[3*i+1] = (WORD)f[i][1];
		idx[3*i+2] = (WORD)f[i][2];
	}
	MESHGROUP grp;
	memset (&grp, 0, sizeof(grp));
	grp.Vtx = vtx;
	grp.Idx = idx;
	grp.nVtx = 12;
	grp.nIdx = 60;
	grp.MtrlIdx = 0;      // first material (added below)
	grp.TexIdx = 0;       // no texture
	MESHHANDLE hMesh = oapiCreateMesh (1, &grp);
	if (!hMesh) return;
	MATERIAL mat;
	memset (&mat, 0, sizeof(mat));
	mat.diffuse  = { 1.0f, 0.45f, 0.05f, 1.0f };   // bright orange (visibility)
	mat.specular = { 0.5f, 0.22f, 0.03f, 1.0f };
	mat.ambient  = { 0.3f, 0.14f, 0.02f, 1.0f };
	mat.power    = 20.0f;
	oapiAddMaterial (hMesh, &mat);   // material index 0
	AddMesh (hMesh);
}

