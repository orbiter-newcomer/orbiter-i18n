// Wreck.cpp
// A minimal debris vessel: each instance generates a random
// polyhedron mesh at creation time, so every wreck piece looks
// different (and is re-generated for every explosion).
// ==============================================================

#define STRICT
#define ORBITER_MODULE

#include "orbitersdk.h"
